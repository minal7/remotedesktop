import Foundation

/// Current host-observed binding, refreshed at authorization and permit consumption.
struct VaultFillCurrentBinding: Sendable, Equatable {
    var ownerID: String
    var sessionID: String
    var taskID: String
    var revision: Int64
    var targetReference: String
    var navigationGeneration: Int64
    var frameGeneration: Int64
    var targetIdentity: VaultFillTargetIdentity
    var handleID: VaultItemID
    var field: VaultSecretField

    init(draft: VaultFillApprovalDraft) {
        ownerID = draft.ownerID; sessionID = draft.sessionID; taskID = draft.taskID
        revision = draft.revision; targetReference = draft.targetReference
        navigationGeneration = draft.navigationGeneration; frameGeneration = draft.frameGeneration
        targetIdentity = draft.targetIdentity; handleID = draft.handleID; field = draft.field
    }
}

struct VaultFillApprovalBinding: Sendable, Equatable {
    let current: VaultFillCurrentBinding
    let approvalID: UUID
    let nonce: UUID
}

/// A phone-facing challenge is a value-free binding. Its identifier is generated by the host.
struct VaultFillApprovalChallenge: Sendable, CustomStringConvertible, CustomDebugStringConvertible {
    fileprivate let draft: VaultFillApprovalDraft
    fileprivate let useState: VaultFillChallengeUseState
    let binding: VaultFillApprovalBinding
    let expiresAt: Date
    let consentClass: VaultFillConsentClass

    init(draft: VaultFillApprovalDraft) {
        self.draft = draft
        useState = draft.useState
        binding = VaultFillApprovalBinding(current: VaultFillCurrentBinding(draft: draft),
            approvalID: draft.approvalID, nonce: draft.nonce)
        expiresAt = draft.expiresAt
        consentClass = draft.consentClass
    }

    var description: String { "<vault-fill-approval-challenge>" }
    var debugDescription: String { description }
}

/// Opaque authenticated phone evidence. The verifier owns all cryptographic/Face ID trust decisions;
/// no Boolean from a model or client is accepted as proof by this lifecycle.
struct VaultFillApprovalReceipt: Sendable, CustomStringConvertible, CustomDebugStringConvertible {
    let binding: VaultFillApprovalBinding
    // Kept module-internal so only an injected trusted verifier can inspect it.
    let evidence: Data

    init(binding: VaultFillApprovalBinding, proof: Data) {
        self.binding = binding; evidence = proof
    }

    init(challenge: VaultFillApprovalChallenge, proof: Data) {
        self.init(binding: challenge.binding, proof: proof)
    }

    var description: String { "<vault-fill-approval-receipt>" }
    var debugDescription: String { description }
}

/// Injection boundary only. This module ships no verifier implementation; production integration
/// must supply an authenticated, challenge-bound phone receipt and fresh Face ID evidence.
protocol VaultFillTrustedApprovalVerifier: Sendable {
    /// Verifies a fresh owner approval for an address/phone fill.
    func verifyOwnerApproval(_ receipt: VaultFillApprovalReceipt,
                             for challenge: VaultFillApprovalChallenge) throws
    /// Verifies owner approval plus a fresh phone Face ID assertion bound to this challenge.
    func verifyFreshPhoneBiometric(_ receipt: VaultFillApprovalReceipt,
                                   for challenge: VaultFillApprovalChallenge) throws
}

enum VaultFillRuntimeStatus: Sendable, Equatable {
    case active, revoked, stopped, takenOver, denied, disconnected
}

struct VaultFillRuntimeSnapshot: Sendable, Equatable {
    let binding: VaultFillCurrentBinding
    let status: VaultFillRuntimeStatus
}

enum VaultFillInvalidationReason: Sendable, Equatable {
    case denied, stop, takeover, navigation, focusChanged, disconnected, taskRevoked, targetChanged
    case memoryForgotten, serviceClosed, serviceUnavailable
}

enum VaultFillAuthorizationError: Error, Sendable, Equatable {
    case receiptMismatch
    case bindingChanged
    case inactiveTask
    case expired
    case challengeAlreadyUsed
    case challengeInUse
    case invalidated(VaultFillInvalidationReason)
    case invalidReceipt
    case invalidClock
    case verificationFailed
    case permitAlreadyConsumed
}

/// One process-local lifetime bound shared by receipt verification and permit use. A challenge
/// cannot outlive either its wall-clock expiry or 30 monotonic seconds from draft creation.
private final class VaultFillClockWindow: @unchecked Sendable {
    private static let maxWallTime: TimeInterval = 4_102_444_800
    private static let maxLifetime: TimeInterval = 30
    private let lock = NSLock()
    private let expiresAt: TimeInterval
    private let now: @Sendable () -> Date
    private let monotonicNow: @Sendable () -> TimeInterval
    private let createdAtWall: TimeInterval
    private let createdAtMonotonic: TimeInterval
    private var previousWall: TimeInterval
    private var previousMonotonic: TimeInterval
    private let monotonicDeadline: TimeInterval
    private var terminalError: VaultFillAuthorizationError?

    init(draft: VaultFillApprovalDraft, now: @escaping @Sendable () -> Date,
         monotonicNow: @escaping @Sendable () -> TimeInterval) {
        expiresAt = draft.expiresAt.timeIntervalSince1970
        createdAtWall = draft.createdAtWall.timeIntervalSince1970
        createdAtMonotonic = draft.createdAtMonotonic
        self.now = now; self.monotonicNow = monotonicNow
        let wall = now().timeIntervalSince1970
        let monotonic = monotonicNow()
        previousWall = wall; previousMonotonic = monotonic

        let lifetime = expiresAt - createdAtWall
        guard expiresAt.isFinite, expiresAt >= 0, expiresAt <= Self.maxWallTime,
              createdAtWall.isFinite, createdAtWall >= 0, createdAtWall <= Self.maxWallTime,
              lifetime > 0, lifetime <= Self.maxLifetime,
              createdAtMonotonic.isFinite, createdAtMonotonic >= 0,
              wall.isFinite, wall >= createdAtWall, wall <= Self.maxWallTime,
              monotonic.isFinite, monotonic >= createdAtMonotonic else {
            monotonicDeadline = createdAtMonotonic
            terminalError = .invalidClock
            return
        }
        let remaining = expiresAt - createdAtWall
        guard remaining > 0 else {
            monotonicDeadline = createdAtMonotonic
            terminalError = .expired
            return
        }
        let deadline = createdAtMonotonic + min(Self.maxLifetime, remaining)
        guard deadline.isFinite, deadline >= createdAtMonotonic else {
            monotonicDeadline = createdAtMonotonic
            terminalError = .invalidClock
            return
        }
        monotonicDeadline = deadline
        if wall >= expiresAt || monotonic >= deadline { terminalError = .expired }
    }

    func validate() throws {
        lock.lock(); defer { lock.unlock() }
        if let terminalError { throw terminalError }
        let wall = now().timeIntervalSince1970
        let monotonic = monotonicNow()
        guard wall.isFinite, wall >= createdAtWall, wall <= Self.maxWallTime,
              monotonic.isFinite, monotonic >= createdAtMonotonic,
              wall >= previousWall, monotonic >= previousMonotonic else {
            terminalError = .invalidClock
            throw VaultFillAuthorizationError.invalidClock
        }
        previousWall = wall; previousMonotonic = monotonic
        guard wall < expiresAt, monotonic < monotonicDeadline else {
            terminalError = .expired
            throw VaultFillAuthorizationError.expired
        }
    }
}

/// Serializes receipt verification and approval use. Integration must connect every host lifecycle
/// event to `invalidate` and consume the permit at its final synchronous action fence.
final class VaultFillAuthorizationLifecycle: @unchecked Sendable {
    private let challenge: VaultFillApprovalChallenge
    private let useState: VaultFillChallengeUseState
    private let currentRuntime: @Sendable () -> VaultFillRuntimeSnapshot
    private let verifier: any VaultFillTrustedApprovalVerifier
    private let clockWindow: VaultFillClockWindow
    private let revocationDomain: VaultFillRevocationDomain?

    init(challenge: VaultFillApprovalChallenge,
         currentRuntime: @escaping @Sendable () -> VaultFillRuntimeSnapshot,
         verifier: any VaultFillTrustedApprovalVerifier,
         revocationDomain: VaultFillRevocationDomain? = nil,
         now: @escaping @Sendable () -> Date = { Date() },
         monotonicNow: @escaping @Sendable () -> TimeInterval = { ProcessInfo.processInfo.systemUptime }) {
        self.challenge = challenge; self.currentRuntime = currentRuntime
        useState = challenge.useState
        self.verifier = verifier
        self.revocationDomain = revocationDomain
        clockWindow = VaultFillClockWindow(draft: challenge.draft, now: now,
            monotonicNow: monotonicNow)
    }

    func authorize(_ receipt: VaultFillApprovalReceipt) throws -> VaultFillPermit {
        try checkCancellationAndInvalidateChallenge()
        try validateServiceActivity()
        useState.lock.lock()
        switch useState.phase {
        case .pending:
            guard receipt.binding == challenge.binding else {
                useState.lock.unlock(); throw VaultFillAuthorizationError.receiptMismatch
            }
            useState.phase = .verifying
        case .verifying:
            useState.lock.unlock(); throw VaultFillAuthorizationError.challengeInUse
        case .used:
            useState.lock.unlock(); throw VaultFillAuthorizationError.challengeAlreadyUsed
        case .invalidated(let reason):
            useState.lock.unlock(); throw VaultFillAuthorizationError.invalidated(reason)
        }
        useState.lock.unlock()

        // Cancellation between claiming the challenge and entering verification is terminal too.
        try checkCancellationAndInvalidateChallenge()
        try validateCurrentRuntime()
        guard !receipt.evidence.isEmpty, receipt.evidence.count <= 8_192 else {
            invalidate(.denied)
            throw VaultFillAuthorizationError.invalidReceipt
        }
        try checkCancellationAndInvalidateChallenge()
        do {
            switch challenge.consentClass {
            case .freshPhoneBiometricRequired:
                try verifier.verifyFreshPhoneBiometric(receipt, for: challenge)
            case .originApprovalRequired:
                try verifier.verifyOwnerApproval(receipt, for: challenge)
            }
        } catch is CancellationError {
            invalidate(.taskRevoked)
            throw CancellationError()
        } catch {
            useState.lock.lock()
            let failure: VaultFillAuthorizationError
            if case .verifying = useState.phase {
                useState.phase = .invalidated(.denied)
                failure = .verificationFailed
            } else if let existing = invalidationReason(useState.phase) {
                failure = .invalidated(existing)
            } else {
                failure = .verificationFailed
            }
            useState.lock.unlock()
            throw failure
        }

        // The task/target may have changed while the verifier was checking the receipt.
        try checkCancellationAndInvalidateChallenge()
        try validateServiceActivity()
        try validateCurrentRuntime()

        let permitState = VaultFillPermitState()
        let issuePermit = {
            self.useState.lock.lock(); defer { self.useState.lock.unlock() }
            if Task<Never, Never>.isCancelled {
                self.useState.phase = .invalidated(.taskRevoked)
                throw CancellationError()
            }
            guard case .verifying = self.useState.phase else {
                let existing = self.invalidationReason(self.useState.phase)
                throw VaultFillAuthorizationError.invalidated(existing ?? .denied)
            }
            self.useState.phase = .used
            self.useState.permitState = permitState
            return VaultFillPermit(expectedBinding: self.challenge.binding.current,
                clockWindow: self.clockWindow, state: permitState,
                currentRuntime: self.currentRuntime, revocationDomain: self.revocationDomain)
        }
        if let revocationDomain {
            do { return try revocationDomain.withActive(issuePermit) }
            catch let error as VaultFillAuthorizationError {
                invalidate(reason: error)
                throw error
            }
        }
        return try issuePermit()
    }

    /// Stop, Deny, takeover and all target/task changes invalidate pending or issued authority.
    func invalidate(_ reason: VaultFillInvalidationReason) {
        useState.lock.lock(); defer { useState.lock.unlock() }
        useState.permitState?.invalidate(reason)
        switch useState.phase {
        case .pending, .verifying: useState.phase = .invalidated(reason)
        case .used, .invalidated: break
        }
    }

    private func validateCurrentRuntime() throws {
        do { try clockWindow.validate() }
        catch let error as VaultFillAuthorizationError {
            invalidate(.taskRevoked)
            throw error
        }
        let snapshot = currentRuntime()
        guard snapshot.status == .active else {
            let reason: VaultFillInvalidationReason
            switch snapshot.status {
            case .revoked: reason = .taskRevoked
            case .stopped: reason = .stop
            case .takenOver: reason = .takeover
            case .denied: reason = .denied
            case .disconnected: reason = .disconnected
            case .active: return
            }
            invalidate(reason)
            throw VaultFillAuthorizationError.inactiveTask
        }
        guard snapshot.binding == challenge.binding.current else {
            invalidate(.targetChanged)
            throw VaultFillAuthorizationError.bindingChanged
        }
    }

    private func validateServiceActivity() throws {
        do { try revocationDomain?.requireActive() }
        catch let error as VaultFillAuthorizationError {
            invalidate(reason: error)
            throw error
        }
    }

    private func invalidate(reason error: VaultFillAuthorizationError) {
        guard case .invalidated(let reason) = error else { return }
        invalidate(reason)
    }

    private func checkCancellationAndInvalidateChallenge() throws {
        do { try Task<Never, Never>.checkCancellation() }
        catch {
            invalidate(.taskRevoked)
            throw CancellationError()
        }
    }

    private func invalidationReason(_ state: VaultFillChallengeUseState.Phase) -> VaultFillInvalidationReason? {
        if case .invalidated(let reason) = state { return reason }
        return nil
    }
}

/// Bounded service lifetime state shared by issued lifecycles and permits. It retains no
/// per-challenge objects; each use checks the local terminal reason and the store's durable fence.
final class VaultFillRevocationDomain: @unchecked Sendable {
    private let lock = NSLock()
    private let validateStore: @Sendable () throws -> Void
    private var reason: VaultFillInvalidationReason?

    init(validateStore: @escaping @Sendable () throws -> Void) {
        self.validateStore = validateStore
    }

    func requireActive() throws {
        lock.lock()
        if let reason { lock.unlock(); throw VaultFillAuthorizationError.invalidated(reason) }
        lock.unlock()

        do { try validateStore() }
        catch {
            let invalidation: VaultFillInvalidationReason
            if let storeError = error as? MemoryStoreError {
                switch storeError {
                case .erasurePending: invalidation = .memoryForgotten
                case .closed: invalidation = .serviceClosed
                default: invalidation = .serviceUnavailable
                }
            } else { invalidation = .serviceUnavailable }
            revoke(invalidation)
            throw VaultFillAuthorizationError.invalidated(invalidation)
        }

        lock.lock(); defer { lock.unlock() }
        if let reason { throw VaultFillAuthorizationError.invalidated(reason) }
    }

    func withActive<T>(_ operation: () throws -> T) throws -> T {
        try requireActive()
        lock.lock(); defer { lock.unlock() }
        if let reason { throw VaultFillAuthorizationError.invalidated(reason) }
        return try operation()
    }

    func revoke(_ invalidation: VaultFillInvalidationReason) {
        lock.lock(); defer { lock.unlock() }
        if reason == nil { reason = invalidation }
    }
}

fileprivate final class VaultFillPermitState: @unchecked Sendable {
    private let lock = NSLock()
    private var consumed = false
    private var invalidation: VaultFillInvalidationReason?

    func invalidate(_ reason: VaultFillInvalidationReason) {
        lock.lock(); defer { lock.unlock() }
        if !consumed, invalidation == nil { invalidation = reason }
    }

    func consume(_ validate: () throws -> Void,
                 fencedCommit: (((() throws -> Void) throws -> Void))? = nil) throws {
        do {
            try Task<Never, Never>.checkCancellation()
            try validate()
            try Task<Never, Never>.checkCancellation()
        } catch is CancellationError {
            invalidate(.taskRevoked)
            throw CancellationError()
        }

        let commit = {
            self.lock.lock(); defer { self.lock.unlock() }
            if let invalidation = self.invalidation {
                throw VaultFillAuthorizationError.invalidated(invalidation)
            }
            guard !self.consumed else { throw VaultFillAuthorizationError.permitAlreadyConsumed }
            if Task<Never, Never>.isCancelled {
                self.invalidation = .taskRevoked
                throw CancellationError()
            }
            self.consumed = true
        }
        do {
            if let fencedCommit { try fencedCommit(commit) }
            else { try commit() }
        } catch let error as VaultFillAuthorizationError {
            if case .invalidated(let reason) = error { invalidate(reason) }
            throw error
        } catch is CancellationError {
            invalidate(.taskRevoked)
            throw CancellationError()
        }
    }
}

/// Shared by every immutable draft/challenge wrapper so rewrapping cannot reset single-use state.
final class VaultFillChallengeUseState: @unchecked Sendable {
    fileprivate enum Phase { case pending, verifying, used, invalidated(VaultFillInvalidationReason) }
    fileprivate let lock = NSLock()
    fileprivate var phase: Phase = .pending
    fileprivate var permitState: VaultFillPermitState?
}

/// Opaque, single-use, value-free permit. It is not a setter or a secret resolver. The host must
/// consume it at the final serialized synchronous input fence and perform the setter in that same
/// operation; it must not consume and then await, look up, or write before acting.
struct VaultFillPermit: Sendable, CustomStringConvertible, CustomDebugStringConvertible {
    private let expectedBinding: VaultFillCurrentBinding
    private let clockWindow: VaultFillClockWindow
    private let state: VaultFillPermitState
    private let currentRuntime: @Sendable () -> VaultFillRuntimeSnapshot
    private let revocationDomain: VaultFillRevocationDomain?

    fileprivate init(expectedBinding: VaultFillCurrentBinding,
                     clockWindow: VaultFillClockWindow,
                     state: VaultFillPermitState,
                     currentRuntime: @escaping @Sendable () -> VaultFillRuntimeSnapshot,
                     revocationDomain: VaultFillRevocationDomain? = nil) {
        self.expectedBinding = expectedBinding; self.clockWindow = clockWindow; self.state = state
        self.currentRuntime = currentRuntime
        self.revocationDomain = revocationDomain
    }

    func consume() throws {
        let validateRuntime = {
            do { try self.clockWindow.validate() }
            catch {
                self.state.invalidate(.taskRevoked)
                throw VaultFillAuthorizationError.invalidated(.taskRevoked)
                }
            let snapshot = self.currentRuntime()
            guard snapshot.status == .active else {
                let reason: VaultFillInvalidationReason
                switch snapshot.status {
                case .active: reason = .taskRevoked
                case .revoked: reason = .taskRevoked
                case .stopped: reason = .stop
                case .takenOver: reason = .takeover
                case .denied: reason = .denied
                case .disconnected: reason = .disconnected
                }
                self.state.invalidate(reason)
                throw VaultFillAuthorizationError.invalidated(reason)
            }
            guard snapshot.binding == self.expectedBinding else {
                self.state.invalidate(.targetChanged)
                throw VaultFillAuthorizationError.invalidated(.targetChanged)
            }
        }
        if let revocationDomain {
            try state.consume(validateRuntime, fencedCommit: { commit in
                try revocationDomain.withActive(commit)
            })
        } else {
            try state.consume(validateRuntime)
        }
    }

    var description: String { "<vault-fill-permit>" }
    var debugDescription: String { description }
}
